import { createHash } from "node:crypto";
import type { Plugin } from "obsidian";
import {
  normalizeVaultFolder,
  vaultFoldersOverlap,
} from "../../features/coforge/domain/vault-folder-policy";
import {
  record,
  list,
  text,
  oneOf,
  shape,
} from "../../features/coforge/domain/check";
import { renderPublicSite } from "../../features/coforge/domain/public-site";
import { renderLegacyPublicSite } from "./public-site-legacy";
import { publicExportBoardCheck } from "./public-export-board-check";
import { renderPreProjectPublicSite } from './public-site-pre-projects';

export const PUBLIC_DATA_FILES = ["board.json", "index.html"] as const;
type DataFile = (typeof PUBLIC_DATA_FILES)[number];
export interface PublicExportReceipt {
  folder: string;
  publicProjectIds: string[];
  files: Partial<Record<DataFile, string[]>>;
}
const digest = (content: string) =>
  createHash("sha256").update(content).digest("hex");
const fingerprint = text({ pattern: /^[a-f0-9]{64}$/u });
const folderKey = (folder: string) =>
  folder
    .split("/")
    .map((segment) => segment.replace(/[. ]+$/u, "").toLowerCase())
    .join("/");
const receiptCheck = shape(
  {
    folder: text({ min: 1, max: 200 }),
    publicProjectIds: list(text({ min: 1, max: 200 }), { max: 10000 }),
    files: record,
  },
  { strict: true },
);

/** Private receipts bind generated bytes to exact paths, including an interrupted publication. */
export class PublicExportOwnership {
  constructor(private readonly plugin: Plugin) {}
  private get adapter() {
    return this.plugin.app.vault.adapter;
  }
  private get path() {
    return `${this.plugin.manifest.dir ?? `${this.plugin.app.vault.configDir}/plugins/${this.plugin.manifest.id}`}/coforge-public-exports.json`;
  }
  async readFile(folder: string, name: DataFile): Promise<string | null> {
    const path = `${folder}/${name}`;
    return (await this.adapter.exists(path)) ? this.adapter.read(path) : null;
  }
  async load(): Promise<PublicExportReceipt[]> {
    if (!(await this.adapter.exists(this.path))) return [];
    const input = shape(
      {
        format: oneOf(["coforge-public-export-ownership/v1"] as const),
        exports: list(receiptCheck, { max: 1000 }),
      },
      { strict: true },
    )(JSON.parse(await this.adapter.read(this.path)));
    return input.exports.map((item) => {
      const folder = normalizeVaultFolder(item.folder);
      if (
        folder !== item.folder ||
        [this.plugin.app.vault.configDir, ".git"].some((path) =>
          vaultFoldersOverlap(folder, path),
        )
      )
        throw new Error(
          "Public export ownership paths need repair; no files were removed.",
        );
      const files: PublicExportReceipt["files"] = {};
      for (const [name, hashes] of Object.entries(item.files)) {
        if (name !== "board.json" && name !== "index.html")
          throw new Error(
            "Public export ownership names need repair; no files were removed.",
          );
        files[name] = list(fingerprint, { min: 1, max: 2 })(hashes);
      }
      return { folder, files, publicProjectIds: item.publicProjectIds };
    });
  }
  async save(exports: PublicExportReceipt[]): Promise<void> {
    const next = JSON.stringify(
      { format: "coforge-public-export-ownership/v1", exports },
      null,
      2,
    );
    if (
      (await this.adapter.exists(this.path)) &&
      (await this.adapter.read(this.path)) === next
    )
      return;
    await this.adapter.write(this.path, next);
  }
  async legacy(folder: string): Promise<PublicExportReceipt | null> {
    if (
      [this.plugin.app.vault.configDir, ".git"].some((path) =>
        vaultFoldersOverlap(folder, path),
      )
    )
      return null;
    const json = await this.readFile(folder, "board.json");
    const html = await this.readFile(folder, "index.html");
    let marked =
      html?.includes("Read-only view generated by CoForge.") ?? false;
    if (!json && !html) return null;
    try {
      const input = record(JSON.parse(json ?? "null"));
      if (input.format !== "coforge-public-board/v1") {
        if (marked) throw new Error("marked");
        return null;
      }
      marked = true;
      // Parsing the whole known renderer is stricter than trusting a filename or footer marker.
      const preProject = !Object.hasOwn(input, 'projectId');
      const board = publicExportBoardCheck(preProject ? { ...input, projectId: '' } : input);
      // That renderer predates community contexts; never adopt data it would hide.
      const matches = preProject
        ? board.columns.every(column => column.ideas.every(idea => idea.contexts === undefined)) && html === renderPreProjectPublicSite(board)
        : html === renderPublicSite(board) || html === renderLegacyPublicSite(board);
      if (
        !html ||
        !matches
      )
        throw new Error("edited");
      return {
        folder,
        publicProjectIds: board.projectId ? [board.projectId] : [],
        files: { "board.json": [digest(json!)], "index.html": [digest(html)] },
      };
    } catch {
      if (marked)
        throw new Error(
          "A generated public export was edited or cannot be verified. Preserve its human changes and restore the generated files before changing project privacy.",
        );
      return null;
    }
  }
  async validate(
    receipt: PublicExportReceipt,
    requireVacant = false,
  ): Promise<void> {
    for (const name of PUBLIC_DATA_FILES) {
      const content = await this.readFile(receipt.folder, name);
      if (
        content !== null &&
        (receipt.files[name] || requireVacant) &&
        !receipt.files[name]?.includes(digest(content))
      )
        throw new Error(
          "A generated public export changed outside CoForge. Preserve its human changes before changing project privacy.",
        );
    }
  }
  async plan(
    folder: string,
    contents: Record<DataFile, string>,
    publicProjectIds: string[],
  ): Promise<PublicExportReceipt[]> {
    const receipts = await this.load();
    let receipt = receipts.find((item) => item.folder === folder);
    if (!receipt) {
      const alias = receipts.find(
        (item) => folderKey(item.folder) === folderKey(folder),
      );
      receipt = alias
        ? { ...structuredClone(alias), folder }
        : ((await this.legacy(folder)) ?? {
            folder,
            files: {},
            publicProjectIds: [],
          });
      receipts.push(receipt);
    }
    await this.validate(receipt, true);
    for (const item of receipts.filter(
      (entry) => folderKey(entry.folder) === folderKey(folder),
    )) {
      await this.validate(item);
      for (const name of PUBLIC_DATA_FILES) {
        if (item !== receipt && !item.files[name]) continue;
        const before = await this.readFile(item.folder, name);
        item.files[name] = [
          ...new Set([
            ...(before === null ? [] : [digest(before)]),
            digest(contents[name]),
          ]),
        ];
      }
    }
    receipt.publicProjectIds = publicProjectIds;
    await this.save(receipts);
    return receipts;
  }
}
