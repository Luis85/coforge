import { expect, test } from '@playwright/test';
import { AxeBuilder } from '@axe-core/playwright';
import { mkdir } from 'node:fs/promises';
import { openWorkflowDisclosure, openWorkflowSettings } from '../support/workflow-navigation';
import { parseWorkflowDefinition } from '../../../src/plugin/features/coforge/domain/configured-workflow';

for (const [theme, width] of [['light', 1280], ['dark', 360]] as const) test(`analytical defaults and explicit opt-outs remain usable in ${theme} at ${width}px without dispatch`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 }); await page.goto('/#surface=node-1');
  await expect(page.locator('html')).toHaveAttribute('data-prototype-ready', 'true');
  await page.evaluate(theme => { document.body.classList.toggle('theme-light', theme === 'light'); document.body.classList.toggle('theme-dark', theme === 'dark'); }, theme);
  await openWorkflowSettings(page);
  await page.locator('[data-step-id="plan"] .cf-workflow-step-select').click();
  const access = page.locator('summary').filter({ hasText: /^Agent and project access$/ });
  if (await access.locator('..').getAttribute('open') === null) await access.click();
  await page.getByLabel('AI provider', { exact: true }).selectOption('claude');
  const tools = page.getByRole('region', { name: 'Analytical agent tools', exact: true });
  const assistants = tools.getByRole('checkbox', { name: 'Allow provider-native assistants', exact: true });
  const research = tools.getByRole('checkbox', { name: 'Allow native web research', exact: true });
  await expect(assistants).toBeChecked(); await expect(research).toBeChecked();
  await expect(tools).toContainText('do not allow shell commands or repository writes');
  await assistants.focus(); await expect(assistants).toBeFocused();
  await page.keyboard.press('Tab'); await expect(research).toBeFocused();
  expect(await tools.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await mkdir('reports/analytical-agent-tools', { recursive: true });
  await tools.screenshot({ path: `reports/analytical-agent-tools/defaults-${theme}-${width}.png` });
  expect((await new AxeBuilder({ page }).include('.cf-workflow-page').withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()).violations).toEqual([]);
  await assistants.uncheck(); await research.uncheck();
  await page.getByRole('button', { name: 'Save workflow', exact: true }).click();
  await expect(page.locator('.cf-workflow-editor-notice')).toContainText('Workflow saved.');
  await openWorkflowDisclosure(page, 'Workflow tools');
  await page.getByRole('button', { name: 'Preview workflow export', exact: true }).click();
  const saved = parseWorkflowDefinition(await page.getByLabel('Workflow export JSON', { exact: true }).textContent() ?? '');
  expect(saved.steps.find(step => step.id === 'plan')).toMatchObject({ provider: 'claude', nativeTools: { delegation: false, research: false } });
  await page.getByRole('button', { name: 'Close JSON panel', exact: true }).click();
  await page.locator('.cf-sidebar').getByRole('button', { name: /^Idea board/ }).click();
  await openWorkflowSettings(page);
  await page.locator('[data-step-id="plan"] .cf-workflow-step-select').click();
  await expect(page.getByLabel('Allow provider-native assistants', { exact: true })).not.toBeChecked();
  await expect(page.getByLabel('Allow native web research', { exact: true })).not.toBeChecked();
});

for (const [theme, width] of [['light', 1280], ['dark', 360]] as const) test(`text-only improvement tools save and re-enable in ${theme} at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 }); await page.goto('/#surface=node-1');
  await expect(page.locator('html')).toHaveAttribute('data-prototype-ready', 'true');
  await page.evaluate(theme => { document.body.classList.toggle('theme-light', theme === 'light'); document.body.classList.toggle('theme-dark', theme === 'dark'); }, theme);
  await openWorkflowSettings(page);
  await page.getByLabel('Enable Improve & polish', { exact: true }).check();
  await page.getByLabel('Improvement provider', { exact: true }).selectOption('claude');
  const panel = page.getByRole('region', { name: 'Improve & polish configuration', exact: true });
  const options = panel.locator('[aria-label="Text-only improvement tools"]');
  await expect(options).not.toHaveAttribute('open');
  const summary = options.locator('summary'); await summary.focus(); await summary.press('Enter');
  const assistants = options.getByLabel('Improvement Allow provider-native assistants', { exact: true });
  const research = options.getByLabel('Improvement Allow native web research', { exact: true });
  await expect(assistants).toBeChecked(); await expect(research).toBeChecked();
  expect(await options.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await mkdir('reports/analytical-agent-tools', { recursive: true });
  await options.screenshot({ path: `reports/analytical-agent-tools/text-improvement-${theme}-${width}.png` });
  expect((await new AxeBuilder({ page }).include('[aria-label="Improve & polish configuration"]').withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()).violations).toEqual([]);
  await assistants.uncheck(); await research.uncheck();
  await expect(panel.getByLabel('Improvement Maximum concurrent native assistants', { exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Save workflow', exact: true }).click();
  await expect(page.locator('.cf-workflow-editor-notice')).toContainText('Workflow saved.');
  await page.locator('.cf-sidebar').getByRole('button', { name: /^Idea board/ }).click(); await openWorkflowSettings(page);
  await panel.locator('[aria-label="Text-only improvement tools"] summary').click();
  await expect(assistants).not.toBeChecked(); await expect(research).not.toBeChecked();
  await research.check(); await assistants.check();
  await expect(panel.getByLabel('Improvement Maximum concurrent native assistants', { exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Save workflow', exact: true }).click();
  await expect(page.locator('.cf-workflow-editor-notice')).toContainText('Workflow saved.');
  await openWorkflowDisclosure(page, 'Workflow tools');
  await page.getByRole('button', { name: 'Preview workflow export', exact: true }).click();
  const saved = parseWorkflowDefinition(await page.getByLabel('Workflow export JSON', { exact: true }).textContent() ?? '');
  expect(saved.improvementPass?.nativeTools).toEqual({ delegation: { maxConcurrent: 2 }, research: true });
});
