import { expect, test } from '@playwright/test';
import { openWorkflowAttempts, openWorkflowRuns, openWorkflowSettings } from '../support/workflow-navigation';

test('request runs stay in their own detail and Step attempts inspect reopens the exact request', async ({ page }) => {
  await page.goto('/#surface=node-1');
  await expect(page.locator('html')).toHaveAttribute('data-prototype-ready', 'true');
  await openWorkflowRuns(page, 'CF-101');
  const execution = page.getByRole('region', { name: 'Request workflow execution', exact: true });
  await expect(execution).toContainText('CF-101');
  await execution.getByRole('button', { name: 'Start · Screen', exact: true }).click();
  await expect(execution.getByRole('button', { name: 'Run · Score', exact: true })).toBeEnabled();
  await expect(page.locator('.cf-idea-footer')).toHaveCount(0);
  await openWorkflowRuns(page, 'CF-107');
  await expect(execution).toContainText('CF-107');
  await expect(execution).not.toContainText('CF-101');
  await expect(execution.getByRole('button', { name: 'Start · Screen', exact: true })).toBeEnabled();
  await expect(execution.getByRole('button', { name: 'Run · Score', exact: true })).toHaveCount(0);
  await expect(execution.getByLabel('Workflow request', { exact: true })).toHaveCount(0);
  await openWorkflowAttempts(page);
  const attempt = page.locator('.cf-workflow-history-row').filter({ hasText: 'CF-101' }).first();
  await attempt.locator('summary').click();
  await attempt.getByRole('button', { name: 'Open idea', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Idea sections', exact: true }).getByRole('button', { name: 'Workflow runs', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(execution).toContainText('CF-101');
  await expect(execution.getByRole('button', { name: 'Run · Score', exact: true })).toBeEnabled();
});

test('definition, timing and independent template drafts survive flat-tab navigation', async ({ page }) => {
  await page.goto('/#surface=node-1');
  await expect(page.locator('html')).toHaveAttribute('data-prototype-ready', 'true');
  await openWorkflowSettings(page);
  const nav = page.getByRole('navigation', { name: 'Agent workflow pages', exact: true });
  await expect(nav.getByRole('button')).toHaveText(['Idea Board Workflow', 'Step attempts', 'Timing & limits', 'Answer / output templates', 'Herdr']);
  await page.getByLabel('Workflow name', { exact: true }).fill('Preserved definition draft');
  await nav.getByRole('button', { name: 'Timing & limits', exact: true }).click();
  const timeout = page.locator('[data-workflow-field="limits.timeoutSeconds"]');
  await expect(timeout).toBeVisible();
  await timeout.fill('240');
  await nav.getByRole('button', { name: 'Answer / output templates', exact: true }).click();
  const library = page.locator('.cf-workflow-template-library');
  await expect(library).toHaveAttribute('open', '');
  await library.getByRole('button', { name: 'New template', exact: true }).click();
  await library.getByLabel('Template name', { exact: true }).fill('Independent template draft');
  await library.getByLabel('Template Markdown', { exact: true }).fill('# Preserved output');
  await nav.getByRole('button', { name: 'Timing & limits', exact: true }).click();
  await expect(timeout).toHaveValue('240');
  await nav.getByRole('button', { name: 'Idea Board Workflow', exact: true }).click();
  await expect(page.getByLabel('Workflow name', { exact: true })).toHaveValue('Preserved definition draft');
  await nav.getByRole('button', { name: 'Answer / output templates', exact: true }).click();
  await expect(library.getByLabel('Template name', { exact: true })).toHaveValue('Independent template draft');
  await expect(library.getByLabel('Template Markdown', { exact: true })).toHaveValue('# Preserved output');
  await library.getByRole('button', { name: 'Save template', exact: true }).click();
  await expect(library.locator('.cf-workflow-editor-notice')).toContainText('Template saved.');
  await nav.getByRole('button', { name: 'Idea Board Workflow', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save workflow', exact: true })).toBeEnabled();
  await expect(page.getByLabel('Workflow name', { exact: true })).toHaveValue('Preserved definition draft');
  await nav.getByRole('button', { name: 'Timing & limits', exact: true }).click();
  await expect(timeout).toHaveValue('240');
});
