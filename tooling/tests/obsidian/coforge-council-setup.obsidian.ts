import { expect as browserExpect } from '@playwright/test';
import { describe, expect } from 'vitest';
import { test } from './support/obsidian-fixture';
import { openCouncilPage } from '../../../tests/e2e/support/council-navigation';

describe('Council first-use setup in the contained host', () => {
  test('configures a CoWorker, project roster and Council through the UI before asking', async ({ obsidian }) => {
    const view = await obsidian.openView(`${obsidian.pluginId}-view-project-workbench`);
    await view.locator('.cf-project-switcher').click();
    await view.getByRole('button', { name: 'Add project', exact: true }).click();
    await view.getByLabel('Project name', { exact: true }).fill('First Council project');
    await view.getByLabel(/^Project path/).fill('/synthetic/first-council');
    await view.getByLabel('Description', { exact: true }).fill('Contained first-use setup with simulation only.');
    await view.getByRole('button', { name: 'Create project', exact: true }).click();
    await browserExpect(view.locator('.cf-project-switcher')).toContainText('First Council project');
    await view.getByRole('button', { name: 'The Council', exact: true }).click();
    await openCouncilPage(view, 'Definitions');
    const readiness = view.getByRole('region', { name: 'Council setup readiness', exact: true });
    await browserExpect(readiness).toContainText('No enabled CoWorkers');
    await browserExpect(view.getByRole('button', { name: 'Create council', exact: true })).toBeDisabled();
    await readiness.getByRole('button', { name: 'Manage CoWorkers', exact: true }).click();
    await view.getByRole('button', { name: 'Create CoWorker', exact: true }).click();
    await view.getByLabel('Definition name', { exact: true }).fill('Setup adviser');
    await view.getByLabel('Role', { exact: true }).fill('Product review');
    await view.getByLabel('CoWorker instructions', { exact: true }).fill('Compare tradeoffs and identify missing information without implementation.');
    await view.getByRole('combobox', { name: 'Provider', exact: true }).selectOption('demo');
    await view.getByLabel('Available for new runs', { exact: true }).check();
    await view.getByRole('button', { name: 'Save CoWorker', exact: true }).click();
    await browserExpect(view.locator('.cf-coworker-cards')).toContainText('Setup adviser');
    await view.getByRole('button', { name: 'The Council', exact: true }).click();
    await openCouncilPage(view, 'Definitions');
    await browserExpect(readiness).toContainText('1 enabled CoWorker');
    await readiness.getByRole('button', { name: 'Create default team', exact: true }).click();
    await browserExpect(view.locator('.cf-council-definition-list')).toContainText('Studio team');
    await readiness.getByRole('button', { name: 'Edit project roster', exact: true }).click();
    await view.getByLabel('Setup adviser', { exact: true }).check();
    await view.getByRole('button', { name: 'Save definition', exact: true }).click();
    await browserExpect(readiness).toContainText('Enabled roster with available CoWorkers');
    await view.getByRole('button', { name: 'Create council', exact: true }).click();
    await view.getByLabel('Definition name', { exact: true }).fill('First Council');
    await view.getByLabel('Available for new runs', { exact: true }).check();
    await browserExpect(view.getByRole('region', { name: 'Council rounds', exact: true })).toContainText('Opinions');
    await browserExpect(view.getByRole('region', { name: 'Council rounds', exact: true })).toContainText('Solutions');
    await view.getByRole('button', { name: 'Save definition', exact: true }).click();
    await browserExpect(readiness).toContainText('1 configured Council');
    await browserExpect(readiness).toContainText('Provider readiness is checked separately');
    await openCouncilPage(view, 'Ask the Council');
    const intake = view.getByRole('region', { name: 'Ask the Council for advice', exact: true });
    await intake.getByRole('combobox', { name: 'Council', exact: true }).selectOption({ label: 'First Council' });
    const recipients = intake.getByRole('region', { name: 'Selected Council recipients', exact: true });
    await browserExpect(recipients).toContainText('First Council');
    await browserExpect(recipients).toContainText('Setup adviser');
    await browserExpect(recipients).toContainText('Simulation · no model call');
    await browserExpect(intake.getByRole('combobox', { name: 'Project team', exact: true })).toHaveCount(0);
    await intake.getByLabel('Task title', { exact: true }).fill('First question');
    await intake.getByLabel('Your question or task', { exact: true }).fill('Compare the two options and explain assumptions.');
    await intake.getByRole('button', { name: 'Save task and review', exact: true }).click();
    await browserExpect(view.getByRole('region', { name: 'Invocation preview', exact: true })).toContainText('2 invocations');
    await browserExpect(view.getByRole('button', { name: 'Submit reviewed task', exact: true })).toBeDisabled();
    await browserExpect(view.getByRole('button', { name: 'Queue simulation', exact: true })).toBeDisabled();
    const attempts = await obsidian.eval(async ({ app, pluginId }) => {
      const path = `${app.vault.configDir}/plugins/${pluginId}/coforge-execution-v2.json`;
      if (!await app.vault.adapter.exists(path)) return { runs: 0, attempts: 0 };
      const envelope = JSON.parse(await app.vault.adapter.read(path));
      const journal = typeof envelope.payload === 'string' ? JSON.parse(envelope.payload) : envelope.payload;
      return { runs: journal.runs.length, attempts: journal.runs.reduce((count: number, run: { attempts: unknown[] }) => count + run.attempts.length, 0) };
    });
    expect(attempts).toEqual({ runs: 0, attempts: 0 });
    expect(obsidian.errors()).toEqual([]);
    await obsidian.screenshot('council-first-use-ready-for-explicit-review');
  });
});
